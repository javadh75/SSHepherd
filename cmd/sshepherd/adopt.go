// newUsers turns the plan's unknown keys into manifest users, described by
// where they were found.
func newUsers(plan adopt.Plan) []config.User {
	users := make([]config.User, 0, len(plan.NewUsers))
	for _, nu := range plan.NewUsers {
		users = append(users, config.User{
			Name:        nu.Name,
			Description: "adopted from " + strings.Join(nu.FoundOn, ", "),
			Keys:        []string{nu.Line},
		})
	}
	return users
}

// extensionsAndGrants is the plan's access additions: extensions of known
// users first, then each new user's grant — the servers it was found on, by
// name (never "*", D5).
func extensionsAndGrants(plan adopt.Plan) []config.Access {
	access := make([]config.Access, 0, len(plan.Extensions)+len(plan.NewUsers))
	for _, e := range plan.Extensions {
		access = append(access, config.Access{User: e.User, Servers: e.Servers})
	}
	for _, nu := range plan.NewUsers {
		access = append(access, config.Access{User: nu.Name, Servers: nu.FoundOn})
	}
	return access
}

// generateAdoptManifest renders the input manifest plus the adoption plan:
// existing sections verbatim, then new users, extensions, and new grants,
// through the one encoder (manifest.GenerateWith) driven by the config types,
// so every schema field — authorized_keys_file included — round-trips.
// serial: and revoked: are copied from the loaded manifest (never from a
// server's header), so regenerating never erases revocation memory.
// gaps (only non-empty under --partial, see gapNotes) name servers whose
// access is missing from the output, as manifest comments so the gap
// survives stderr.
func generateAdoptManifest(cfg *config.Config, plan adopt.Plan, src string, gaps []string) ([]byte, error) {
	users := append(slices.Clone(cfg.Users), newUsers(plan)...)
	access := append(slices.Clone(cfg.Access), extensionsAndGrants(plan)...)
	var header strings.Builder
	fmt.Fprintf(&header, "# generated by sshepherd adopt from %s — review before use\n", src)
	for _, g := range gaps {
		header.WriteString("# " + g + "\n")
	}
	return manifest.GenerateWith(header.String(), manifest.Draft{ //nolint:wrapcheck // "encode manifest: …"
		Serial: cfg.Serial(), Users: users, Groups: cfg.Groups, Servers: cfg.Servers, Access: access, Revoked: cfg.Tombstones,
	})
}

// renderMergedManifest renders the plan as a comment-preserving append to
// the original manifest text (--merge): existing bytes kept — comments
// intact, no regenerated header — with the plan's new users and grants
// appended under a dated merge marker. An empty plan returns raw unchanged,
// byte for byte. date is injected (never read from the clock here) so tests
// and goldens stay deterministic. gaps (only non-empty under --partial, see
// gapNotes) are comment lines on the marker, so the gap survives stderr
// exactly as in regenerate mode.
func renderMergedManifest(mf *manifest.File, raw []byte, plan adopt.Plan, gaps []string, date string) ([]byte, error) {
	if len(plan.NewUsers) == 0 && len(plan.Extensions) == 0 {
		return raw, nil
	}
	comments := append([]string{"merged by sshepherd adopt on " + date}, gaps...)
	if err := mf.Append(comments, newUsers(plan), nil, extensionsAndGrants(plan)); err != nil {
		return nil, fmt.Errorf("merge manifest: %w", err)
	}
	out, err := mf.Encode()
	if err != nil {
		return nil, fmt.Errorf("merge manifest: %w", err)
	}
	return out, nil
}

// reportUnreadable logs each unreadable-server issue (warn under --partial,
// error otherwise) and, absent --partial, escalates to the strict abort: a
// draft generated from a partial read under-represents reality, so a later
// apply would revoke keys we never saw.
func reportUnreadable(log *slog.Logger, plan adopt.Plan, unreadable []string, partial bool) error {
	if len(unreadable) == 0 {
		return nil
	}
	// Deliberate double-report: the live warn (audit fan-out) shows failures
	// as they happen; these gate lines are the verdict that explains the
	// abort/partial decision — and the only lines that survive -q in strict
	// mode.
	emit := log.Error
	if partial {
		emit = log.Warn
	}
	for _, is := range plan.Issues {
		emit(fmt.Sprintf("server %s: %s", is.Server, is.Detail))
	}
	// Each distinct hint once, after the issue lines, the way audit.Hints
	// dedupes them in the text report: a fleet-wide outage gets one dial
	// hint, not one per server.
	seen := make(map[string]bool)
	for _, is := range plan.Issues {
		if is.Hint == "" || seen[is.Hint] {
			continue
		}
		seen[is.Hint] = true
		emit("hint: " + is.Hint)
	}
	if !partial {
		log.Error(apply.Plural(len(unreadable), "server", "servers") +
			" could not be fully read — nothing written; fix the errors above or re-run with --partial")
		return errFleetUnreadable
	}
	return nil
}

// loadAdoptManifest reads --config once through the store in both modes:
// --merge needs the original bytes (the output when there is nothing to
// adopt, the append base otherwise) and the node tree, and an in-place
// -o FILE --force saves against those bytes, so a concurrent revoke is
// refused rather than undone. mf is nil without --merge.
func loadAdoptManifest(path string, merge bool) (manifestTarget, *config.Config, *manifest.File, error) {
	m, err := readManifest(path)
	if err != nil {
		return manifestTarget{}, nil, nil, manifestError("--config", path, err)
	}
	if !merge {
		cfg, err := config.Parse(m.Loaded)
		if err != nil {
			return manifestTarget{}, nil, nil, manifestError("--config", path, err)
		}
		return m, cfg, nil, nil
	}
	mf, err := manifest.Load(m.Loaded)
	if err != nil {
		return manifestTarget{}, nil, nil, manifestError("--config", path, err)
	}
	return m, mf.Config(), mf, nil
}

// fleetReadCount counts servers whose read returned without a transport
// error (a server with only an ignored line still counts as read: its other
// keys were seen).
func fleetReadCount(results []audit.ServerResult) int {
	n := 0
	for _, r := range results {
		if r.Err == nil {
			n++
		}
	}
	return n
}

// partlyRead names the servers of unreadable that were read without a
// transport error: only some of their lines (ignored or unparseable) could
// not be used, and their other keys are adopted.
func partlyRead(unreadable []string, results []audit.ServerResult) map[string]bool {
	read := make(map[string]bool, len(results))
	for _, r := range results {
		if r.Err == nil {
			read[r.Server.Name] = true
		}
	}
	partly := make(map[string]bool)
	for _, srv := range unreadable {
		if read[srv] {
			partly[srv] = true
		}
	}
	return partly
}

// gapNotes are the manifest comments naming each server whose access the
// output does not fully represent: an unreadable server is missing whole,
// a partly read one only for the keys on lines adopt could not use.
func gapNotes(unreadable []string, partly map[string]bool) []string {
	notes := make([]string, 0, len(unreadable))
	for _, srv := range unreadable {
		if partly[srv] {
			notes = append(notes, "WARNING: server "+srv+" partly read — keys on lines adopt could not use are NOT represented")
		} else {
			notes = append(notes, "WARNING: server "+srv+" unreadable — its access is NOT represented")
		}
	}
	return notes
}

// reportReadCount logs "read X of N servers" — a warning when some went
// unread or were only partly read — and refuses a --partial run that read
// no server at all: nothing was adopted, so nothing is rendered or written
// (exit 3). A manifest with no servers has nothing to count.
func reportReadCount(log *slog.Logger, total, read, partly int, partial bool) error {
	if total == 0 {
		return nil
	}
	msg := "read " + strconv.Itoa(read) + " of " + apply.Plural(total, "server", "servers")
	var gaps []string
	if read < total {
		gaps = append(gaps, "access on the others is NOT in the output")
	}
	if partly > 0 {
		gaps = append(gaps, apply.Plural(partly, "server", "servers")+" partly read: keys on lines adopt could not use are NOT in the output")
	}
	if len(gaps) > 0 {
		log.Warn(msg + " — " + strings.Join(gaps, "; "))
	} else {
		log.Info(msg)
	}
	if partial && read == 0 {
		return fmt.Errorf("read 0 of %s — nothing could be adopted; fix the errors above", apply.Plural(total, "server", "servers"))
	}
	return nil
}

// reportPlan logs the plan's operator-facing notes: attribution warnings,
// the adoption outcome, and a nothing-to-adopt note qualified when part of
// the fleet went unread.
func reportPlan(log *slog.Logger, plan adopt.Plan, unreadable []string) {
	for _, w := range plan.Warnings {
		log.Warn(w.Message)
	}
	if len(plan.NewUsers) == 0 && len(plan.Extensions) == 0 {
		note := "nothing to adopt: the manifest already accounts for every key found"
		if len(unreadable) > 0 {
			// Unreadable servers may hold keys we never saw; don't let the
			// note read as "the whole fleet is clean".
			note += " on the readable servers"
		}
		log.Info(note)
		return
	}
	log.Info("adopting " + apply.Plural(len(plan.NewUsers), "new user", "new users") + ", " +
		apply.Plural(len(plan.Extensions), "access extension", "access extensions"))
}

// adoptOpts are adopt's own flags; connFlags holds the shared ones.
type adoptOpts struct {
	outPath string
	force   bool
	partial bool
	merge   bool
	json    bool
}

// adoptRun is one adopt run.
type adoptRun struct {
	log    *slog.Logger
	stdout io.Writer
	cf     *connFlags
	opts   adoptOpts
}

func (r *adoptRun) run(ctx context.Context) error {
	ids, err := r.cf.validate()
	if err != nil {
		return err
	}
	m, cfg, mf, err := loadAdoptManifest(r.cf.cfgPath, r.opts.merge)
	if err != nil {
		return err
	}
	logManifest(r.log, cfg)
	results, err := readFleet(ctx, r.log, cfg, cfg.Servers, r.cf, ids, "reading")
	if err != nil {
		return err
	}
	plan := adopt.Build(cfg, results)
	unreadable := plan.UnreadableServers()
	partly := partlyRead(unreadable, results)
	rep := adopt.Report{Mode: adopt.ModeGenerate, Servers: len(cfg.Servers), Read: fleetReadCount(results), PartlyRead: len(partly)}
	if r.opts.merge {
		rep.Mode = adopt.ModeMerge
	}
	if err := reportUnreadable(r.log, plan, unreadable, r.opts.partial); err != nil {
		return r.stop(plan, rep, err)
	}
	if err := reportReadCount(r.log, rep.Servers, rep.Read, rep.PartlyRead, r.opts.partial); err != nil {
		return r.stop(plan, rep, err)
	}
	rendered, err := r.render(m, cfg, mf, plan, gapNotes(unreadable, partly))
	if err != nil {
		return err
	}
	reportPlan(r.log, plan, unreadable)
	// Self-check: never emit a manifest our own loader would reject,
	// nor one that keeps a policy conflict (D29).
	saved, err := config.Parse(rendered)
	if err != nil {
		return fmt.Errorf("bug: generated manifest fails validation: %w", err)
	}
	if err := conflictRefusal(cfg, saved); err != nil {
		return err
	}
	return r.finish(plan, rep, m, rendered)
}

func (r *adoptRun) render(m manifestTarget, cfg *config.Config, mf *manifest.File, plan adopt.Plan, gaps []string) ([]byte, error) {
	if r.opts.merge {
		return renderMergedManifest(mf, m.Loaded, plan, gaps, time.Now().Format("2006-01-02"))
	}
	return generateAdoptManifest(cfg, plan, r.cf.cfgPath, gaps)
}

// stop ends a run that emits no manifest. Under --json the document says
// why, with the exit code the process is about to return: the strict gate
// (1) or a --partial run that read nothing (3, the one exit 3 with a
// document).
func (r *adoptRun) stop(plan adopt.Plan, rep adopt.Report, stopErr error) error {
	if r.opts.json {
		rep.ExitCode = exitCodeFor(stopErr)
		if err := adopt.WriteJSON(r.stdout, plan, rep); err != nil {
			return err //nolint:wrapcheck // "encode adopt report: …"
		}
	}
	return stopErr
}

// finish emits the manifest. The document is written only after -o
// succeeded, so a refused save (exit 3) leaves stdout empty.
func (r *adoptRun) finish(plan adopt.Plan, rep adopt.Report, m manifestTarget, rendered []byte) error {
	var end error
	if r.opts.partial && rep.Read < rep.Servers {
		// The partial manifest is out; the exit code tells a script
		// it is incomplete (exit 1, like audit). A partly read server
		// (only lines adopt could not use) counts as read and keeps
		// exit 0; its gap is marked in the output and on stderr.
		end = fmt.Errorf("%w: read %d of %d servers", errFleetUnreadable, rep.Read, rep.Servers)
	}
	if !r.opts.json {
		if err := emitManifest(r.stdout, m, r.opts.outPath, rendered, r.opts.force); err != nil {
			return err
		}
		return end
	}
	place, err := placeManifest(m, r.opts.outPath, rendered, r.opts.force)
	if err != nil {
		return err
	}
	rep.Emitted, rep.Placement, rep.ExitCode = true, place, exitCodeFor(end)
	if err := adopt.WriteJSON(r.stdout, plan, rep); err != nil {
		return err //nolint:wrapcheck // "encode adopt report: …"
	}
	return end
}

func newAdoptCmd(a *app, stdout io.Writer) *cobra.Command {
	var (
		cf   connFlags
		opts adoptOpts
	)
	cmd := &cobra.Command{
		Use:   "adopt",
		Short: "Generate a manifest that adopts every key already installed on the fleet",
		Long: "Connects to every server in the manifest (same SSH path as audit), reads\n" +
			"the actual authorized_keys, and emits a complete new manifest in which\n" +
			"every installed key is accounted for: keys of known users found beyond\n" +
			"their grants extend that user's access; unknown keys become new users\n" +
			"with access to exactly the servers where they were found. The input\n" +
			"file is modified only when --output names it (with --force); it is then\n" +
			"saved in place under the manifest lock, like revoke. Review the output,\n" +
			"then adopt it as your manifest. Any unreadable server aborts the run\n" +
			"unless --partial is set.\n\n" +
			exitCodesAdopt,
		Example: "  # Bootstrap: append every installed key to a servers-only manifest\n" +
			"  sshepherd adopt --merge -o adopted.yaml\n\n" +
			"  # Regenerate from scratch, even if some servers are down\n" +
			"  sshepherd adopt --partial -o adopted.yaml\n\n" +
			"  # A discovery report for a script; the manifest goes to the file\n" +
			"  sshepherd adopt --merge --json -o adopted.yaml",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			r := &adoptRun{log: a.logger, stdout: stdout, cf: &cf, opts: opts}
			return r.run(cmd.Context())
		},
	}
	cf.register(cmd, "max concurrent server reads")
	cmd.Flags().StringVarP(&opts.outPath, "output", "o", "", "write the manifest to this file instead of stdout")
	cmd.Flags().BoolVar(&opts.force, "force", false, "allow --output to overwrite an existing file")
	cmd.Flags().BoolVar(&opts.partial, "partial", false, "proceed even if some servers cannot be read (their access will be missing from the output)")
	cmd.Flags().BoolVar(&opts.merge, "merge", false, "merge into --config: preserve its text and append what is new")
	cmd.Flags().BoolVar(&opts.json, "json", false, "emit a machine-readable report on stdout (the manifest goes to -o, or into the report's manifest field)")
	return cmd
}
