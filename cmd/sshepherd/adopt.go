// generateAdoptManifest renders the input manifest plus the adoption plan:
// existing sections verbatim, then new users, extensions, and new grants.
// unreadable (only non-empty under --partial) names servers whose access is
// missing from the output, as manifest comments so the gap survives stderr.
func generateAdoptManifest(cfg *config.Config, plan adopt.Plan, src string, unreadable []string) ([]byte, error) {
	m := manifestOut{Users: []userOut{}, Servers: []serverOut{}, Access: []accessOut{}}
	for _, u := range cfg.Users {
		m.Users = append(m.Users, userOut{
			Name: u.Name, Description: u.Description, Comment: u.Comment,
			Operator: u.Operator, Keys: u.Keys,
		})
	}
	for _, nu := range plan.NewUsers {
		m.Users = append(m.Users, userOut{
			Name:        nu.Name,
			Description: "adopted from " + strings.Join(nu.FoundOn, ", "),
			Keys:        []string{nu.Line},
		})
	}
	for _, s := range cfg.Servers {
		so := serverOut{
			Name: s.Name, Description: s.Description, Host: s.Host, User: s.User,
			AuthorizedKeysFile: s.AuthorizedKeysFile, // must round-trip, or adopt would strip every override
		}
		if s.Port != 22 { // validation defaulted 0 to 22 already
			so.Port = s.Port
		}
		m.Servers = append(m.Servers, so)
	}
	for _, a := range cfg.Access {
		m.Access = append(m.Access, accessOut{User: a.User, Servers: a.Servers, Except: a.Except})
	}
	for _, e := range plan.Extensions {
		m.Access = append(m.Access, accessOut{User: e.User, Servers: e.Servers})
	}
	for _, nu := range plan.NewUsers {
		servers := nu.FoundOn
		if nu.Wildcard {
			servers = []string{"*"}
		}
		m.Access = append(m.Access, accessOut{User: nu.Name, Servers: servers})
	}
	var header strings.Builder
	fmt.Fprintf(&header, "# generated by sshepherd adopt from %s — review before use\n", src)
	for _, srv := range unreadable {
		fmt.Fprintf(&header, "# WARNING: server %s unreadable — its access is NOT represented\n", srv)
	}
	return encodeManifest(header.String(), m)
}

// renderMergedManifest renders the plan as a comment-preserving append to
// the original manifest text (--merge): existing bytes kept — comments
// intact, no regenerated header — with the plan's new users and grants
// appended under a dated merge marker. An empty plan returns raw unchanged,
// byte for byte. date is injected (never read from the clock here) so tests
// and goldens stay deterministic. unreadable servers (only non-empty under
// --partial) are named as comment lines on the marker, so the gap survives
// stderr exactly as in regenerate mode.
func renderMergedManifest(mf *manifest.File, raw []byte, plan adopt.Plan, unreadable []string, date string) ([]byte, error) {
	if len(plan.NewUsers) == 0 && len(plan.Extensions) == 0 {
		return raw, nil
	}
	comments := []string{"merged by sshepherd adopt on " + date}
	for _, srv := range unreadable {
		comments = append(comments, fmt.Sprintf("WARNING: server %s unreadable — its access is NOT represented", srv))
	}
	users := make([]config.User, 0, len(plan.NewUsers))
	for _, nu := range plan.NewUsers {
		users = append(users, config.User{
			Name:        nu.Name,
			Description: "adopted from " + strings.Join(nu.FoundOn, ", "),
			Keys:        []string{nu.Line},
		})
	}
	access := make([]config.Access, 0, len(plan.Extensions)+len(plan.NewUsers))
	for _, e := range plan.Extensions {
		access = append(access, config.Access{User: e.User, Servers: e.Servers})
	}
	for _, nu := range plan.NewUsers {
		servers := nu.FoundOn
		if nu.Wildcard {
			servers = []string{"*"}
		}
		access = append(access, config.Access{User: nu.Name, Servers: servers})
	}
	if err := mf.Append(comments, users, nil, access); err != nil {
		return nil, fmt.Errorf("merge manifest: %w", err)
	}
	out, err := mf.Encode()
	if err != nil {
		return nil, fmt.Errorf("merge manifest: %w", err)
	}
	return out, nil
}

// reportUnreadable logs each unreadable-server issue (warn under --partial,
// error otherwise) and, absent --partial, escalates to the strict abort: a
// draft generated from a partial read under-represents reality, so a later
// apply would revoke keys we never saw.
func reportUnreadable(log *slog.Logger, plan adopt.Plan, unreadable []string, partial bool) error {
	if len(unreadable) == 0 {
		return nil
	}
	// Deliberate double-report: the live warn (audit fan-out) shows failures
	// as they happen; these gate lines are the verdict that explains the
	// abort/partial decision — and the only lines that survive -q in strict
	// mode.
	emit := log.Error
	if partial {
		emit = log.Warn
	}
	for _, is := range plan.Issues {
		emit(fmt.Sprintf("server %s: %s", is.Server, is.Detail))
	}
	// Each distinct hint once, after the issue lines, the way audit.Hints
	// dedupes them in the text report: a fleet-wide outage gets one dial
	// hint, not one per server.
	seen := make(map[string]bool)
	for _, is := range plan.Issues {
		if is.Hint == "" || seen[is.Hint] {
			continue
		}
		seen[is.Hint] = true
		emit("hint: " + is.Hint)
	}
	if !partial {
		log.Error(apply.Plural(len(unreadable), "server", "servers") +
			" could not be fully read — nothing written; fix the errors above or re-run with --partial")
		return errFleetUnreadable
	}
	return nil
}

// reportPlan logs the plan's operator-facing notes: attribution warnings,
// the adoption outcome, and a nothing-to-adopt note qualified when part of
// the fleet went unread.
func reportPlan(log *slog.Logger, plan adopt.Plan, unreadable []string) {
	for _, w := range plan.Warnings {
		log.Warn(w)
	}
	if len(plan.NewUsers) == 0 && len(plan.Extensions) == 0 {
		note := "nothing to adopt: the manifest already accounts for every key found"
		if len(unreadable) > 0 {
			// Unreadable servers may hold keys we never saw; don't let the
			// note read as "the whole fleet is clean".
			note += " on the readable servers"
		}
		log.Info(note)
		return
	}
	log.Info("adopting " + apply.Plural(len(plan.NewUsers), "new user", "new users") + ", " +
		apply.Plural(len(plan.Extensions), "access extension", "access extensions"))
}

func newAdoptCmd(a *app, stdout io.Writer) *cobra.Command {
	var (
		cf      connFlags
		outPath string
		force   bool
		partial bool
		merge   bool
	)
	cmd := &cobra.Command{
		Use:   "adopt",
		Short: "Generate a manifest that adopts every key already installed on the fleet",
		Long: "Connects to every server in the manifest (same SSH path as audit), reads\n" +
			"the actual authorized_keys, and emits a complete new manifest in which\n" +
			"every installed key is accounted for: keys of known users found beyond\n" +
			"their grants extend that user's access; unknown keys become new users\n" +
			"with access to exactly the servers where they were found. The input\n" +
			"file is never modified — review the output, then adopt it as your\n" +
			"manifest. Any unreadable server aborts the run unless --partial is set.\n\n" +
			exitCodesAdopt,
		Example: "  # Bootstrap: append every installed key to a servers-only manifest\n" +
			"  sshepherd adopt --merge -o adopted.yaml\n\n" +
			"  # Regenerate from scratch, even if some servers are down\n" +
			"  sshepherd adopt --partial -o adopted.yaml",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			ids, err := cf.validate()
			if err != nil {
				return err
			}
			log := a.logger
			var (
				cfg *config.Config
				mf  *manifest.File
				raw []byte
			)
			if merge {
				// --merge needs the original bytes: they are the output when
				// there is nothing to adopt, and the append base otherwise.
				m, err := readManifest(cf.cfgPath)
				if err != nil {
					return manifestError("--config", cf.cfgPath, err)
				}
				raw = m.Loaded
				mf, err = manifest.Load(raw)
				if err != nil {
					return manifestError("--config", cf.cfgPath, err)
				}
				cfg = mf.Config()
			} else {
				cfg, err = config.Load(cf.cfgPath)
				if err != nil {
					return manifestError("--config", cf.cfgPath, err)
				}
			}
			logManifest(log, cfg)
			results, err := readFleet(cmd.Context(), log, cfg, &cf, ids, "reading")
			if err != nil {
				return err
			}
			plan := adopt.Build(cfg, results)
			unreadable := plan.UnreadableServers()
			if err := reportUnreadable(log, plan, unreadable, partial); err != nil {
				return err
			}
			var rendered []byte
			if merge {
				rendered, err = renderMergedManifest(mf, raw, plan, unreadable, time.Now().Format("2006-01-02"))
			} else {
				rendered, err = generateAdoptManifest(cfg, plan, cf.cfgPath, unreadable)
			}
			if err != nil {
				return err
			}
			reportPlan(log, plan, unreadable)
			// Self-check: never emit a manifest our own loader would reject.
			if _, err := config.Parse(rendered); err != nil {
				return fmt.Errorf("bug: generated manifest fails validation: %w", err)
			}
			if outPath == "" {
				if _, err := stdout.Write(rendered); err != nil {
					return fmt.Errorf("write stdout: %w", err)
				}
				return nil
			}
			return writeFileNoClobber(outPath, rendered, force)
		},
	}
	cf.register(cmd, "max concurrent server reads")
	cmd.Flags().StringVarP(&outPath, "output", "o", "", "write the manifest to this file instead of stdout")
	cmd.Flags().BoolVar(&force, "force", false, "allow --output to overwrite an existing file")
	cmd.Flags().BoolVar(&partial, "partial", false, "proceed even if some servers cannot be read (their access will be missing from the output)")
	cmd.Flags().BoolVar(&merge, "merge", false, "preserve the manifest text (comments intact) and append the additions instead of regenerating")
	return cmd
}
