// utf16LE is s with a UTF-16LE byte order mark: bytes yaml.v3 loads and a
// JSON string cannot carry.
func utf16LE(s string) []byte {
	out := []byte{0xFF, 0xFE}
	for _, u := range utf16.Encode([]rune(s)) {
		out = binary.LittleEndian.AppendUint16(out, u)
	}
	return out
}

