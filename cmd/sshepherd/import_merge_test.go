// mergeImportHosts exercises every server rule at once against
// commentedMergeSrc: web-1 identical (skipped), db-1 conflicting (dropped,
// manifest kept), app-1 net-new (appended).
func mergeImportHosts() []sshcfg.Host {
	return []sshcfg.Host{
		{Alias: "web-1", HostName: "10.0.0.1", User: "deploy"},
		{Alias: "db-1", HostName: "10.0.0.99", Port: 2222, User: "deploy"},
		{Alias: "app-1", HostName: "10.0.0.5", Port: 2200, User: "deploy"},
	}
}

// mergeImportUsers exercises every user rule: alice's key under another name
// (extension + warning), bob's key on an absorbed wildcard server (note),
// a new key with a partially conflicted list (partial survival), a new key
// whose only server conflicts (skipped), and a new key colliding with a
// manifest name (renamed, grant cascades).
func mergeImportUsers(t *testing.T) []identity.User {
	t.Helper()
	return []identity.User{
		{Name: "javad-alice", Source: "~/.ssh/alice", Key: testkeys.Line(t, 2), Servers: []string{"app-1", "web-1"}},
		{Name: "javad-bob", Source: "~/.ssh/bob", Key: testkeys.Line(t, 4), Servers: []string{"app-1"}},
		{Name: "javad-carol", Source: "~/.ssh/carol", Comment: "carol@laptop",
			Key: testkeys.Line(t, 7) + " carol@laptop", Servers: []string{"app-1", "db-1"}},
		{Name: "javad-doomed", Source: "~/.ssh/doomed", Key: testkeys.Line(t, 8), Servers: []string{"db-1"}},
		{Name: "alice", Source: "~/.ssh/stray", Key: testkeys.Line(t, 9), Servers: []string{"app-1"}},
	}
}

// TestRenderMergedImportGolden: --merge rendering keeps the original text
// (comments intact, no regenerated header) and appends the reconciled plan
// under a dated merge marker carrying the conflict warnings; the date is
// injected so the golden is deterministic.
func TestRenderMergedImportGolden(t *testing.T) {
	src := commentedMergeSrc(t)
	mf, err := manifest.Load(src)
	if err != nil {
		t.Fatalf("manifest.Load: %v", err)
	}
	plan, err := reconcile.Build(mf.Config(), mergeImportHosts(), mergeImportUsers(t))
	if err != nil {
		t.Fatalf("reconcile.Build: %v", err)
	}
	got, err := renderMergedImport(mf, src, plan, "~/.ssh/config", "2026-07-19")
	if err != nil {
		t.Fatalf("renderMergedImport: %v", err)
	}
	for _, want := range []string{
		"# fleet manifest — hand-maintained; comments must survive a merge",
		"# op holds the break-glass key",
		"# wildcard user, except db-1",
		"# reviewed 2026-07-01",
		"# merged by sshepherd import from ~/.ssh/config on 2026-07-19",
		`# WARNING: server "db-1" in the ssh config differs from the manifest (host/port/user) — manifest kept`,
		`# WARNING: user "javad-doomed" not added: its only server "db-1" conflicts with the manifest`,
		`# WARNING: user name "alice" already taken, using "alice-2" for the incoming key`,
	} {
		if !strings.Contains(string(got), want) {
			t.Errorf("merged output lacks %q:\n%s", want, got)
		}
	}
	if strings.Contains(string(got), "generated by sshepherd import") {
		t.Errorf("merge must not stack a regenerated header:\n%s", got)
	}
	out, err := config.Parse(got)
	if err != nil {
		t.Fatalf("merged manifest rejected by config.Parse: %v", err)
	}
	// app-1 desired: op(1, operator) + alice extension(2 keys) + bob
	// wildcard(1) + javad-carol(1) + alice-2(1) = 6.
	if n := len(out.DesiredFor("app-1")); n != 6 {
		t.Errorf("DesiredFor(app-1) = %d keys, want 6", n)
	}
	// db-1 unchanged: op(1) + carol's manifest grant... db-1 keeps op + the
	// manifest carol grant; bob stays excepted, dropped grants never landed.
	if n := len(out.DesiredFor("db-1")); n != 1 {
		t.Errorf("DesiredFor(db-1) = %d keys, want 1 (op only; the conflicted grants must not land)", n)
	}
	checkGolden(t, "import_merge.golden", got)
}

