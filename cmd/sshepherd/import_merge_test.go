// TestRenderMergedImportIdempotent: re-running the same merge against its
// own output is a byte-identical no-op — the plan is empty (conflict and
// steady-state findings persist, but nothing is appended).
func TestRenderMergedImportIdempotent(t *testing.T) {
	src := commentedMergeSrc(t)
	mf, err := manifest.Load(src)
	if err != nil {
		t.Fatalf("manifest.Load: %v", err)
	}
	plan, err := reconcile.Build(mf.Config(), mergeImportHosts(), mergeImportUsers(t))
	if err != nil {
		t.Fatalf("reconcile.Build: %v", err)
	}
	merged, err := renderMergedImport(mf, src, plan, "~/.ssh/config", "2026-07-19")
	if err != nil {
		t.Fatalf("renderMergedImport: %v", err)
	}

	mf2, err := manifest.Load(merged)
	if err != nil {
		t.Fatalf("manifest.Load(merged): %v", err)
	}
	plan2, err := reconcile.Build(mf2.Config(), mergeImportHosts(), mergeImportUsers(t))
	if err != nil {
		t.Fatalf("reconcile.Build (re-run): %v", err)
	}
	if !plan2.Empty() {
		t.Fatalf("re-run plan = %+v, want empty (idempotency)", plan2)
	}
	again, err := renderMergedImport(mf2, merged, plan2, "~/.ssh/config", "2026-07-20")
	if err != nil {
		t.Fatalf("renderMergedImport (re-run): %v", err)
	}
	if !bytes.Equal(again, merged) {
		t.Errorf("re-run is not byte-identical:\n--- got ---\n%s\n--- want ---\n%s", again, merged)
	}
}

